// ── Shared KudiAI Report/Statement PDF Engine ─────────────────────────────────
// Single source of truth for every report and statement across the platform.
// Usage:
//   const pdf = await createReportPdf({ title, businessName, period, logoUrl, entityDetails })
//   pdf.addStats([{ label, value, color?, bg? }])
//   pdf.addSectionTitle("Section")
//   pdf.addTable(cols, rows)           // cols: { key, label, w, right?, bold?, color? }
//   pdf.addTotalsBlock(rows)           // rows: { label, value, bold?, highlight?, sep?, green?, red? }
//   pdf.addBarChart(bars)
//   pdf.addEntityPanel(details)        // [{label,value}] — account holder card
//   pdf.addStatement(txns, opts)       // opts: { openingBalance?, totalDebits?, totalCredits? }
//   await pdf.save("filename.pdf")
//
// Owner reports (2026-10-02) pass `letterhead` + `verifyRef` for the receipt-style look:
//   letterhead: { businessName, logoUrl, address, phone, email, generatedAt } — the business's own logo, name, address and
//               contacts on the left; report title, period, generated date-time and reference on the right
//   verifyRef:  "KDR-YYYYMM-XXXXXXXX" — footer on every page: KudiAI logo, "Generated by KudiAI Track · A product of
//               Amaya & Co. Technologies", the verify link and a QR code that opens it (report_verifications table)
// Without them a report keeps the original header/footer (statements elsewhere in the app use that).
// ─────────────────────────────────────────────────────────────────────────────
// The drawing lives in src/shared/reportPdfCore.js (also run on the server for the monthly business report email);
// this file loads the assets in the browser — the KudiAI logo, NotoSans, the business's logo, the verify QR — and saves.

import { savePdf } from "./pdfSave";
import { loadImageAsset, downscaleImage } from "./pdfAssets";
import { qrMatrix } from "./qrMatrix";
import { createReportPdfCore, fmtCurrency, fmtDate, fmtGeneratedAt } from "../shared/reportPdfCore.js";

