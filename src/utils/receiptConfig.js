// ── Debt repayment (from Credit screen) ────────────────────────────────────
export function buildCreditPaymentReceipt(payment, credit, businessName, biz) {
  const { ref, hasRef, image, pdf } = receiptFilenames(payment.id, payment.created_at || payment.payment_date, 'Debt Repayment', payment.receipt_ref);
  // What the debtor still owes after this payment: stored at write time; older
  // payments fall back to the outstanding figure on the credit record.
  const stored = numOrNull(payment.balance_after);
  const remaining = stored != null ? stored
    : (credit?.outstanding != null && payment.amount != null) ? credit.outstanding - payment.amount : null;
  const method = payment.payment_method ? humanize(payment.payment_method) : null;

  return {
    title:     'Debt Repayment',
    direction: 'in',
    status:    'success',
    amount:    payment.amount,
    datetime:  formatReceiptDateTime(payment.created_at || payment.payment_date),
    fields: [
      { label: 'Transaction Type', value: 'Debt Repayment' },
      credit?.customer_name  && { label: 'Customer',          value: credit.customer_name },
      method                 && { label: 'Payment Method',    value: method },
      remaining != null      && { label: 'Remaining Balance', value: fmtAmt(remaining) },
      payment.notes          && { label: 'Note',              value: payment.notes },
                                { label: 'Reference',          value: ref, copy: hasRef },
    ].filter(Boolean),
    businessName,
    issuedBy:      businessName,
    fees:          0,
    receiptRef:    ref,
    filenames:     { image, pdf },
    processorName: null,
    iconType:      'credit',
    ...meta(payment, { hasRef, method, balanceAfter: remaining, balanceLabel: 'Remaining Balance', biz }),
  };
}

