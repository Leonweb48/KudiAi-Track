// Which processor actually moved the money. Never assume one: a receipt that
// names the wrong processor is worse than one that names none.
const PROCESSORS = {
  wallet:      { label: 'KudiAI Wallet',   line: 'Paid from your KudiAI Wallet' },
  paystack:    { label: 'Paystack',        line: 'Payment securely processed via Paystack' },
  flutterwave: { label: 'Flutterwave',     line: 'Payment securely processed via Flutterwave' },
  cashback:    { label: 'KudiAI cashback', line: 'Paid with KudiAI cashback' },
  cash:        { label: 'Cash',            line: 'Paid in cash' },
};

/** 'wallet' | 'paystack' | … -> { label, line }, or null when the funding source is not recorded. */
export function processorFor(via) {
  return PROCESSORS[String(via || '').toLowerCase()] || null;
}

// The timestamp on every receipt is the stored server time, in WAT, with seconds.
// A date-only value (a row still in the offline queue has no server timestamp yet)
// carries no clock time, so only the date is shown — never an invented time.
export function formatReceiptDateTime(dt) {
  if (!dt) return '—';
  if (/^\d{4}-\d{2}-\d{2}$/.test(String(dt))) return formatWATDate(dt);
  return formatWAT(dt);
}

// A receipt's reference is generated by the database when the row is created and
// stored on it (receipt_ref, KDT-YYYYMM-XXXXXXXX). It is never derived on the device.
// A row that has not reached the server yet has none, and the receipt says so.
export const REF_PENDING = 'Assigned on sync';

// Filenames are `<title>_<ref>_<YYYYMMDD-HHMM>.<ext>` (WAT), e.g.
//   airtime-top-up_KDT-202609-X7K2M9PQ_20260918-2114.pdf
export function receiptFilenames(id, createdAt, title, storedRef) {
  const slug = String(title || 'receipt')
    .toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 28) || 'receipt';
  const cleanRef = String(storedRef || '').replace(/[^A-Za-z0-9-]/g, '');
  const idPart = cleanRef || String(id || '').replace(/[^A-Za-z0-9]/g, '').slice(0, 8).toUpperCase() || 'pending';
  const base = `${slug}_${idPart}_${watStamp(createdAt) || 'undated'}`;
  return { ref: cleanRef || REF_PENDING, hasRef: !!cleanRef, image: `${base}.png`, pdf: `${base}.pdf` };
}

const numOrNull = (v) => (v === null || v === undefined || v === '' || !Number.isFinite(Number(v)) ? null : Number(v));

// The business's own contact details, from a profile row (owner/staff/manager portals).
export function bizFromProfile(profile) {
  return {
    address: profile?.business_address || profile?.address || '',
    phone:   profile?.business_phone   || profile?.phone   || '',
  };
}

// The extra facts the PDF prints, common to every receipt: the stored server
// timestamp, how it was paid, the balance after this entry, and the business's
// contact details when the caller has them. Absent facts stay null and are left
// off the PDF rather than shown as a dash.
function meta(row, { hasRef, method, balanceAfter, balanceLabel, biz } = {}) {
  return {
    hasRef:          !!hasRef,
    occurredAt:      row?.created_at || null,
    method:          method || null,
    balanceAfter:    numOrNull(balanceAfter),
    balanceLabel:    balanceLabel || 'Balance After',
    businessAddress: biz?.address || null,
    businessPhone:   biz?.phone || null,
  };
}

// Locale-independent: always produces ₦15,000.00 regardless of WebView locale.
function fmtAmt(n) {
  const [int, dec] = Number(n || 0).toFixed(2).split('.');
  return '₦' + int.replace(/\B(?=(\d{3})+(?!\d))/g, ',') + '.' + dec;
}

function humanize(s) {
  if (!s) return '—';
  return String(s).replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
}

// ── Standard transaction (income/expense from Transactions screen) ─────────────
// How a cash-book row was paid. A bill row's payment_type is just "bill_payment"
// (the category, not a method), so its method comes from the recorded funding
// source; a legacy bill row that never recorded one shows no method at all.
function transactionMethod(txn) {
  if (txn.payment_type === 'bill_payment') return billPaidVia(txn) ? processorFor(billPaidVia(txn)).label : null;
  return txn.payment_type ? humanize(txn.payment_type) : null;
}

// The funding source of a bill: recorded in bill_details at payment time; older
// wallet-paid rows are recognisable from their note. Anything else is unknown —
// never guessed.
function billPaidVia(bill) {
  const recorded = bill.paidVia || bill.bill_details?.paid_via;
  if (processorFor(recorded)) return String(recorded).toLowerCase();
  if (/paid from wallet/i.test(bill.note || '')) return 'wallet';
  return null;
}

// The structured facts of a stored bill (a transactions row): the note carries them as "Key: value | Key: value" (and the printed pins after
// "__PINS__"), bill_details is the authoritative source when present. Shared by the Bills page and the general history so the same bill
// makes the same receipt wherever it is opened.
export function parseBillRecord(bill) {
  const raw = bill.note || '';
  const pinsIdx = raw.indexOf('__PINS__');
  const n = pinsIdx !== -1 ? raw.slice(0, pinsIdx) : raw;
  const pick = (rx) => n.match(rx)?.[1]?.trim() || '';

  let pinsArr;
  if (pinsIdx !== -1) {
    try { pinsArr = JSON.parse(raw.slice(pinsIdx + 8)); } catch (_) { /* a damaged pin list is left off */ }
  }
  const bd = bill.bill_details || {};

  return {
    paidVia:       bd.paid_via || undefined,
    apiRef:        bd.orderId || pick(/Ref:\s*([^\s|]+)/i),
    token:         bd.token || (() => { const t = (pick(/Token:\s*([^|]+)/i) || '').trim(); return t && !t.toLowerCase().startsWith('loading') ? t : undefined; })(),
    units:         bd.units || (pick(/Units:\s*([^|]+)/i) || '').trim() || undefined,
    network:       pick(/Network:\s*([^|]+)/i),
    phone:         pick(/Phone:\s*([^|]+)/i) || pick(/Beneficiary:\s*([^|]+)/i),
    planName:      pick(/Plan:\s*([^|]+)/i),
    smartcard:     pick(/Smartcard:\s*([^|]+)/i),
    meterNo:       pick(/Meter:\s*([^|]+)/i),
    meterAddress:  pick(/Meter Address:\s*([^|]+)/i),
    meterTypeName: pick(/Type:\s*([^|]+)/i),
    providerName:  pick(/Provider:\s*([^|]+)/i),
    platformName:  pick(/Platform:\s*([^|]+)/i),
    packageName:   pick(/Package:\s*([^|]+)/i),
    customerId:    pick(/Customer:\s*([^|]+)/i),
    accountNo:     pick(/Account:\s*([^|]+)/i),
    value:         pick(/Value:\s*([^|]+)/i),
    pinsArr:       bd.pins || pinsArr,
    cardDetails:   bd.cardDetails || undefined,
  };
}

export function buildTransactionReceipt(txn, profile) {
  // A bill opened from the general history is the same receipt as on the Bills page: its provider's logo, the smartcard / meter / token
  // details — not the plain income / expense layout below.
  if (txn.payment_type === 'bill_payment' || (BILL_CATEGORIES.has(txn.category) && txn.type !== 'in')) {
    const biz = bizFromProfile(profile);
    const r = buildBillReceipt({
      ...txn,
      ...parseBillRecord(txn),
      businessName:    profile?.business_name || 'My Business',
      businessAddress: biz.address,
      businessPhone:   biz.phone,
      staffName:       txn.staff_name || undefined,
    });
    return txn._pending ? { ...r, status: 'pending' } : r;
  }
  const isIn   = txn.type === 'in';
  const status =
    txn._pending         ? 'pending' :
    txn.bill_status === 'failed' ? 'failed' : 'success';
  const method = transactionMethod(txn);

  const isMulti = Array.isArray(txn.line_items) && txn.line_items.length > 1;
  const liFields = isMulti
    ? txn.line_items.map(li => ({
        label: li.name ? `${li.name}${(li.qty || 1) > 1 ? ` ×${li.qty}` : ''}` : '—',
        value: fmtAmt(li.lineTotal),
      }))
    : [];
  const title = isMulti
    ? `${txn.line_items.length} items`
    : txn.item_name || humanize(txn.category) || (isIn ? 'Payment Received' : 'Payment Made');
  const { ref, hasRef, image, pdf } = receiptFilenames(txn.id, txn.created_at || txn.transaction_date, title, txn.receipt_ref);
  const balanceAfter = numOrNull(txn.balance_after);
  // A bill paid through the app is booked as an expense row; its receipt follows the same rule as a bill receipt
  const isBillPayment = txn.payment_type === 'bill_payment';

  return {
    title,
    direction:   isIn ? 'in' : 'out',
    status,
    amount:      txn.amount,
    datetime:    formatReceiptDateTime(txn.created_at || txn.transaction_date),
    fields: [
      ...liFields,
      { label: 'Transaction Type', value: isIn ? 'Income' : 'Expense' },
      txn.customer_name && { label: isIn ? 'From'  : 'To',     value: txn.customer_name },
      !isMulti && txn.item_name && { label: 'Description',      value: txn.item_name },
      txn.category      && { label: 'Category',                 value: humanize(txn.category) },
      method            && { label: 'Payment Method',           value: method },
      !isMulti && txn.quantity > 1 && { label: 'Quantity',      value: String(txn.quantity) },
      txn.note          && { label: 'Note',                     value: txn.note },
      txn.staff_name    && { label: 'Recorded by',              value: txn.staff_name },
      balanceAfter != null && { label: 'Balance After',        value: fmtAmt(balanceAfter), private: isBillPayment },
                           { label: 'Reference',                value: ref, copy: hasRef },
    ].filter(Boolean),
    businessName:  profile?.business_name || 'My Business',
    issuedBy:      profile?.business_name || 'My Business',
    fees:          0,
    receiptRef:    ref,
    filenames:     { image, pdf },
    processorName: null,
    iconType:      isIn ? 'income' : 'expense',
    recordedBy:    txn.staff_name || null,
    ...meta(txn, { hasRef, method, balanceAfter, biz: bizFromProfile(profile) }),
    hideBalanceOnShare: isBillPayment,
  };
}

// ── Ajo/Aso contribution or withdrawal (from Aso screen) ─────────────────────
function buildDestinationLabel(contribution) {
  const ctx  = contribution.contribution_context || 'personal_savings';
  const type = contribution.type || '';
  // group_name: flat field some callers pass directly; ajo_groups?.name: the
  // shape a Supabase embedded select (`ajo_groups(name)`) actually returns.
  const grp  = contribution.group_name || contribution.ajo_groups?.name || '';
  const cyc  = contribution.cycle_label || '';
  const rnd  = contribution.round_number ? ` (Round ${contribution.round_number})` : '';

  if (type === 'registration_fee')  return `Registration fee — one-time`;
  if (type === 'commission')         return `Collector's fee — Day 1${cyc ? ` of ${cyc}` : ''}`;
  if (type === 'withdrawal_fee')     return `Withdrawal fee${cyc ? ` — ${contribution.fee_percent ? contribution.fee_percent + '% of ' : ''}${cyc}` : ''}`;
  if ((type === 'disbursement' || type === 'esusu_payout') && grp) {
    if (ctx === 'esusu_rotation') return `Esusu payout — ${grp}${rnd}, your turn`;
    return `Savings group release — ${grp}`;
  }
  if (type === 'group_release' && grp) return `Released from savings group — ${grp}`;
  if (type === 'withdrawal') {
    if (grp) return `From: Released group funds — ${grp}`;
    return `From: Personal Savings${cyc ? ` — ${cyc}` : ''}`;
  }
  if (ctx === 'esusu_rotation')  return `To: Esusu — ${grp}${rnd}`;
  if (ctx === 'group_savings')   return `To: Savings Group — ${grp}`;
  return `To: Personal Savings${cyc ? ` — ${cyc}` : ''}`;
}

export function buildAsoContributionReceipt(contribution, clientName, businessName, recordedByName, biz) {
  const isWithdrawal = contribution.type === 'withdrawal';
  const isReg        = contribution.type === 'registration_fee';
  const status       = contribution.status === 'pending' ? 'pending' : 'success';
  const { ref, hasRef, image, pdf } = receiptFilenames(contribution.id, contribution.created_at || contribution.date, undefined, contribution.receipt_ref);
  const destination  = buildDestinationLabel(contribution);
  const method       = contribution.payment_method ? humanize(contribution.payment_method) : null;
  const balanceAfter = numOrNull(contribution.balance_after);

  return {
    title:     isReg ? 'Registration Fee' : isWithdrawal ? 'Withdrawal' : 'Contribution',
    direction: isWithdrawal ? 'out' : 'in',
    status,
    amount:    contribution.amount,
    datetime:  formatReceiptDateTime(contribution.created_at || contribution.date),
    fields: [
      { label: 'Transaction Type', value: isReg ? 'Registration Fee' : isWithdrawal ? 'Ajo Withdrawal' : 'Ajo Contribution' },
      destination                 && { label: isWithdrawal ? 'From' : 'To',  value: destination },
      clientName                  && { label: 'Member',         value: clientName },
      method                      && { label: 'Payment Method', value: method },
      contribution.notes          && { label: 'Note',           value: contribution.notes },
      recordedByName              && { label: 'Recorded by',    value: recordedByName },
      balanceAfter != null        && { label: 'Balance After',  value: fmtAmt(balanceAfter) },
                                     { label: 'Reference',      value: ref, copy: hasRef },
    ].filter(Boolean),
    businessName,
    issuedBy:      businessName,
    fees:          0,
    receiptRef:    ref,
    filenames:     { image, pdf },
    processorName: null,
    iconType:      'ajo',
    recordedBy:    recordedByName || null,
    ...meta(contribution, { hasRef, method, balanceAfter, biz }),
  };
}

