/**
 * A wallet statement (the owner's, or a client's from the app) — one wallet section.
 * @param holder  businessHolder(...) / clientHolder(...)
 * @param account { number, bank, name }
 * @param period  "1 Oct 2026 – 3 Oct 2026"
 */
export function walletStatementSections({ entries, holder, account, period }) {
  return [{
    title: "WALLET STATEMENT", period, holder, account: walletAccount(account),
    months: groupByMonth(entries),
    emptyText: "There are no wallet transactions in the selected period.",
  }];
}

/** A client's savings statement for a period (client_savings_statement result). */
export function savingsStatementSections(savings, { period } = {}) {
  const entries = savingsEntries(savings?.entries);
  return [{
    title: "SAVINGS STATEMENT", period,
    holder: clientHolder(savings?.client, savings?.business), account: savingsAccount(savings),
    months: groupByMonth(entries, { openingKobo: toKobo(savings?.opening) }),
    emptyText: "There are no savings transactions in the selected period.",
  }];
}

/**
 * The monthly statement a client is sent (client_statement_data result: { month, savings, wallet }): a first page
 * with both accounts at a glance, then the savings and the wallet in full (a month with no entries still shows its
 * balance). A client without a KudiAI wallet is told so on the first page.
 */
export function monthlyStatementSections(data, { titleFor = walletTitle } = {}) {
  const key = data?.month || "";
  const { fromDate, toDate } = monthDates(key);
  const period = periodLabel(fromDate, toDate);
  const s = data?.savings || {};
  const w = data?.wallet || null;
  const holder = clientHolder(s.client, s.business);
  const sa = savingsAccount(s);
  const wa = w ? walletAccount(w.account) : null;
  const rows = (open, tin, tout, close, count) => [
    ["Opening balance", fmtNaira(open), ""],
    ["Money in", fmtNaira(tin), "in"],
    ["Money out", fmtNaira(tout), "out"],
    ["Closing balance", fmtNaira(close), "bold"],
    ["Transactions", String(count), ""],
  ];
  const sections = [{
    kind: "summary", title: "MONTHLY STATEMENT", period, holder,
    account: { title: "ACCOUNTS", lines: [sa.lines[0] || "Savings", wa ? wa.lines[0] : "No KudiAI wallet", sa.lines[1] || ""].filter(Boolean) },
    heading: `${monthKeyLabel(key)} at a glance`,
    panels: [
      { title: "Savings", sub: sa.lines.slice(0, 2).join("  ·  "),
        rows: rows(s.opening, s.total_in, s.total_out, s.closing, (s.entries || []).length) },
      w ? { title: "Wallet", sub: wa.lines.slice(0, 2).join("  ·  "),
            rows: rows(w.opening_kobo / 100, w.in_kobo / 100, w.out_kobo / 100, w.closing_kobo / 100, (w.entries || []).length) }
        : { title: "Wallet", sub: "KudiAI wallet", empty: "You don't have a KudiAI wallet yet. Open one in the app to pay contributions and bills, and to receive payouts." },
    ],
  }, {
    title: "MONTHLY STATEMENT · SAVINGS", period, holder, account: sa,
    months: [singleMonth(key, savingsEntries(s.entries), {
      openingKobo: toKobo(s.opening), closingKobo: toKobo(s.closing), inKobo: toKobo(s.total_in), outKobo: toKobo(s.total_out),
    })],
    emptyText: "No savings transactions this month.",
  }];
  if (w) {
    sections.push({
      title: "MONTHLY STATEMENT · WALLET", period, holder, account: wa,
      months: [singleMonth(key, walletEntries(w.entries, titleFor), {
        openingKobo: w.opening_kobo, closingKobo: w.closing_kobo, inKobo: w.in_kobo, outKobo: w.out_kobo,
      })],
      emptyText: "No wallet transactions this month.",
    });
  }
  return sections;
}

/**
 * @param {any} doc
 * @param {any} data
 * @param {{ logo?: any, font?: string }} assets
 * @param {{ verify?: { ref: string, qr?: { size: number, isDark: Function } } | null, titleFor?: Function }} [opts]
 */
export function renderMonthlyStatementPdf(doc, data, assets, { verify = null, titleFor } = {}) {
  return renderStatementPdf(doc, { sections: monthlyStatementSections(data, { titleFor }), generatedAt: data?.generatedAt, verify }, assets);
}

